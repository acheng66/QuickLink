package quicklink.admin.remote;

import com.baomidou.mybatisplus.extension.plugins.pagination.Page;
import quicklink.admin.common.convention.result.Result;
import quicklink.admin.config.OpenFeignConfiguration;
import quicklink.admin.dto.req.RecycleBinRecoverReqDTO;
import quicklink.admin.dto.req.RecycleBinRemoveReqDTO;
import quicklink.admin.dto.req.RecycleBinSaveReqDTO;
import quicklink.admin.remote.dto.req.QuickLinkBatchCreateReqDTO;
import quicklink.admin.remote.dto.req.QuickLinkCreateReqDTO;
import quicklink.admin.remote.dto.req.QuickLinkUpdateReqDTO;
import quicklink.admin.remote.dto.resp.QuickLinkBatchCreateRespDTO;
import quicklink.admin.remote.dto.resp.QuickLinkCreateRespDTO;
import quicklink.admin.remote.dto.resp.QuickLinkGroupCountQueryRespDTO;
import quicklink.admin.remote.dto.resp.QuickLinkPageRespDTO;
import quicklink.admin.remote.dto.resp.QuickLinkStatsAccessRecordRespDTO;
import quicklink.admin.remote.dto.resp.QuickLinkStatsRespDTO;
import org.springframework.cloud.openfeign.FeignClient;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;

import java.util.List;

/**
 * 短链接中台远程调用服务
 */
@FeignClient(
        value = "quick-link-project",
        url = "${aggregation.remote-url:}",
        configuration = OpenFeignConfiguration.class
)
public interface QuickLinkActualRemoteService {

    /**
     * 创建短链接
     *
     * @param requestParam 创建短链接请求参数
     * @return 短链接创建响应
     */
    @PostMapping("/api/quick-link/v1/create")
    Result<QuickLinkCreateRespDTO> createQuickLink(@RequestBody QuickLinkCreateReqDTO requestParam);

    /**
     * 批量创建短链接
     *
     * @param requestParam 批量创建短链接请求参数
     * @return 短链接批量创建响应
     */
    @PostMapping("/api/quick-link/v1/create/batch")
    Result<QuickLinkBatchCreateRespDTO> batchCreateQuickLink(@RequestBody QuickLinkBatchCreateReqDTO requestParam);

    /**
     * 修改短链接
     *
     * @param requestParam 修改短链接请求参数
     */
    @PostMapping("/api/quick-link/v1/update")
    void updateQuickLink(@RequestBody QuickLinkUpdateReqDTO requestParam);

    /**
     * 分页查询短链接
     *
     * @param gid      分组标识
     * @param orderTag 排序类型
     * @param current  当前页
     * @param size     当前数据多少
     * @return 查询短链接响应
     */
    @GetMapping("/api/quick-link/v1/page")
    Result<Page<QuickLinkPageRespDTO>> pageQuickLink(@RequestParam("gid") String gid,
                                                     @RequestParam("orderTag") String orderTag,
                                                     @RequestParam("current") Long current,
                                                     @RequestParam("size") Long size);

    /**
     * 查询分组短链接总量
     *
     * @param requestParam 分组短链接总量请求参数
     * @return 查询分组短链接总量响应
     */
    @GetMapping("/api/quick-link/v1/count")
    Result<List<QuickLinkGroupCountQueryRespDTO>> listGroupQuickLinkCount(@RequestParam("requestParam") List<String> requestParam);

    /**
     * 根据 URL 获取标题
     *
     * @param url 目标网站地址
     * @return 网站标题
     */
    @GetMapping("/api/quick-link/v1/title")
    Result<String> getTitleByUrl(@RequestParam("url") String url);

    /**
     * 保存回收站
     *
     * @param requestParam 请求参数
     */
    @PostMapping("/api/quick-link/v1/recycle-bin/save")
    void saveRecycleBin(@RequestBody RecycleBinSaveReqDTO requestParam);

    /**
     * 分页查询回收站短链接
     *
     * @param gidList 分组标识集合
     * @param current 当前页
     * @param size    当前数据多少
     * @return 查询短链接响应
     */
    @GetMapping("/api/quick-link/v1/recycle-bin/page")
    Result<Page<QuickLinkPageRespDTO>> pageRecycleBinQuickLink(@RequestParam("gidList") List<String> gidList,
                                                               @RequestParam("current") Long current,
                                                               @RequestParam("size") Long size);

    /**
     * 恢复短链接
     *
     * @param requestParam 短链接恢复请求参数
     */
    @PostMapping("/api/quick-link/v1/recycle-bin/recover")
    void recoverRecycleBin(@RequestBody RecycleBinRecoverReqDTO requestParam);

    /**
     * 移除短链接
     *
     * @param requestParam 短链接移除请求参数
     */
    @PostMapping("/api/quick-link/v1/recycle-bin/remove")
    void removeRecycleBin(@RequestBody RecycleBinRemoveReqDTO requestParam);


    /**
     * 访问单个短链接指定时间内监控数据
     *
     * @param fullShortUrl 完整短链接
     * @param gid          分组标识
     * @param startDate    开始时间
     * @param endDate      结束时间
     * @return 短链接监控信息
     */
    @GetMapping("/api/quick-link/v1/stats")
    Result<QuickLinkStatsRespDTO> oneQuickLinkStats(@RequestParam("fullShortUrl") String fullShortUrl,
                                                    @RequestParam("gid") String gid,
                                                    @RequestParam("enableStatus") Integer enableStatus,
                                                    @RequestParam("startDate") String startDate,
                                                    @RequestParam("endDate") String endDate);

    /**
     * 访问分组短链接指定时间内监控数据
     *
     * @param gid       分组标识
     * @param startDate 开始时间
     * @param endDate   结束时间
     * @return 分组短链接监控信息
     */
    @GetMapping("/api/quick-link/v1/stats/group")
    Result<QuickLinkStatsRespDTO> groupQuickLinkStats(@RequestParam("gid") String gid,
                                                      @RequestParam("startDate") String startDate,
                                                      @RequestParam("endDate") String endDate);

    /**
     * 访问单个短链接指定时间内监控访问记录数据
     *
     * @param fullShortUrl 完整短链接
     * @param gid          分组标识
     * @param startDate    开始时间
     * @param endDate      结束时间
     * @param current      当前页
     * @param size         一页数据量
     * @return 短链接监控访问记录信息
     */
    @GetMapping("/api/quick-link/v1/stats/access-record")
    Result<Page<QuickLinkStatsAccessRecordRespDTO>> quickLinkStatsAccessRecord(@RequestParam("fullShortUrl") String fullShortUrl,
                                                                               @RequestParam("gid") String gid,
                                                                               @RequestParam("startDate") String startDate,
                                                                               @RequestParam("endDate") String endDate,
                                                                               @RequestParam("enableStatus") Integer enableStatus,
                                                                               @RequestParam("current") Long current,
                                                                               @RequestParam("size") Long size);

    /**
     * 访问分组短链接指定时间内监控访问记录数据
     *
     * @param gid       分组标识
     * @param startDate 开始时间
     * @param endDate   结束时间
     * @param current   当前页
     * @param size      一页数据量
     * @return 分组短链接监控访问记录信息
     */
    @GetMapping("/api/quick-link/v1/stats/access-record/group")
    Result<Page<QuickLinkStatsAccessRecordRespDTO>> groupQuickLinkStatsAccessRecord(@RequestParam("gid") String gid,
                                                                                    @RequestParam("startDate") String startDate,
                                                                                    @RequestParam("endDate") String endDate,
                                                                                    @RequestParam("current") Long current,
                                                                                    @RequestParam("size") Long size);
}
